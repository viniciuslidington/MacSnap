#!/usr/bin/env python3
"""Render both static language routes from one template, without dependencies."""
import argparse
import html
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "website"
SITE = ROOT / "site"
PRODUCTION = "https://viniciuslidington.github.io/MacSnap/"
ROUTES = {"en": "", "pt-BR": "pt/"}
PLACEHOLDER = re.compile(r"\{\{([\w.]+)(\|raw)?\}\}")
UI_KEYS = {"copySuccess", "copyFailure", "copied", "showLayouts", "hideLayouts",
           "layoutSelected", "splitValue"}


def render_all():
    template = (SOURCE / "template.html").read_text(encoding="utf-8")
    locales = {
        lang: json.loads((SOURCE / "locales" / f"{lang}.json").read_text(encoding="utf-8"))
        for lang in ROUTES
    }
    expected_keys = set(locales["en"]["copy"])
    output = {}
    for lang, route in ROUTES.items():
        data = locales[lang]
        assert data["language"] == lang
        assert set(data["copy"]) == expected_keys, f"Incomplete static translation: {lang}"
        assert set(data["ui"]) == UI_KEYS, f"Incomplete interactive translation: {lang}"
        assert all(isinstance(s, str) and s.strip() for s in data["copy"].values())
        assert all(isinstance(s, str) and s.strip() for s in data["ui"].values())
        assert set(re.findall(r"\{(\w+)\}", data["ui"]["layoutSelected"])) == {"label"}
        assert set(re.findall(r"\{(\w+)\}", data["ui"]["splitValue"])) == {"first", "second"}
        data = dict(data, canonical=PRODUCTION + route,
                    asset_prefix="../" if route else "",
                    alternate_og_locale="pt_BR" if lang == "en" else "en_US",
                    social_image=PRODUCTION + "assets/social-preview" + ("-pt" if route else "") + ".png",
                    en_href="../" if route else "./", pt_href="./" if route else "pt/",
                    en_current='aria-current="page"' if lang == "en" else "",
                    pt_current='aria-current="page"' if lang == "pt-BR" else "")

        def replace(match):
            key, raw = match.groups()
            if key == "runtime_json":
                # Prevent translated text from closing the inert JSON script element.
                return json.dumps(data["ui"], ensure_ascii=False).replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
            value = data
            for part in key.split("."):
                value = value[part]
            if raw:
                assert key in {"en_current", "pt_current"}, f"Unexpected raw HTML: {key}"
                return value
            return html.escape(value, quote=True)

        rendered = PLACEHOLDER.sub(replace, template)
        assert not PLACEHOLDER.search(rendered), f"Unresolved message in {lang}"
        rendered = rendered.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/build-site-locales.py; edit website/ sources. -->", 1)
        output[SITE / route / "index.html"] = rendered

    entries = []
    for route in ROUTES.values():
        alternates = "".join(
            f'<xhtml:link rel="alternate" hreflang="{lang}" href="{PRODUCTION + target}"/>'
            for lang, target in {**ROUTES, "x-default": ""}.items()
        )
        entries.append(f"  <url><loc>{PRODUCTION + route}</loc>{alternates}</url>")
    output[SITE / "sitemap.xml"] = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        + "\n".join(entries) + "\n</urlset>\n"
    )
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated files without writing them")
    args = parser.parse_args()
    stale = []
    for path, content in render_all().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Run python3 scripts/build-site-locales.py to update: " + ", ".join(stale))
    print("PASS: English and Portuguese pages are current." if args.check else "Rendered English and Portuguese pages.")


if __name__ == "__main__":
    main()
